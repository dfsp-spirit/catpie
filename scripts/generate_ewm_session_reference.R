#!/usr/bin/env Rscript
# Replay one recorded EWM session through the REAL catR package.
#
# Purpose: the pure-Python `catpie` port produces a surprising result on this
# session (a participant answers 33/35 items correctly, yet the ability estimate
# stays at ~0.001 and the next items never get harder). This script shows that
# the R catR package produces the *same* numbers for the *same* item bank and
# the *same* sequence of responses, so the behaviour is caused by the item
# parameters, not by the port.
#
# Input:
#   reference/ewm_session_input.json
#     item_bank     - the 4PL bank, (a, b, c, d) per row, in bank order
#     administered  - 0-based item indices, in administration order
#     responses     - 0/1 responses, same order
#   (generated by the experiment repo:
#    dev_tools/pra/make_catpie_fixture.py)
#
# Output:
#   reference/catr_ewm_session.json
#     per trial: the MFI-selected item, the EAP ability estimate and its SE
#
# The replay mirrors what the experiment does per trial, with catR's defaults:
#   * catR::nextItem(criterion = "MFI")                     item selection
#   * catR::thetaEst(method = "EAP", priorDist = "norm",
#                    priorPar = c(0, 1), D = 1,
#                    parInt = c(-4, 4, 33))                ability estimate
#   * catR::semTheta(method = "EAP", ...)                    standard error
#
# catR indices are 1-based; the fixture uses catpie's 0-based convention and
# this script converts.
#
# Usage:
#   Rscript scripts/generate_ewm_session_reference.R
#
# Requirements: R with the `catR` and `jsonlite` packages installed.

in_json  <- "reference/ewm_session_input.json"
out_json <- "reference/catr_ewm_session.json"

stopifnot(file.exists(in_json))

suppressMessages(library(catR))
suppressMessages(library(jsonlite))

input <- fromJSON(in_json)
bank <- as.matrix(input$item_bank)
colnames(bank) <- c("a", "b", "c", "d")
administered <- as.integer(input$administered)   # 0-based, administration order
responses    <- as.numeric(input$responses)
n_trials     <- length(administered)

cat(sprintf("Item bank: %d items | session: %d trials (%d correct)\n",
            nrow(bank), n_trials, sum(responses)))

PRIOR_DIST <- "norm"
PRIOR_PAR  <- c(0, 1)
D_SCALE    <- 1
PAR_INT    <- c(-4, 4, 33)   # catR's default EAP grid

adm_catr    <- integer(0)     # 1-based, what catR works with
resp_so_far <- numeric(0)
theta       <- 0              # the experiment starts from the prior mean 0
steps       <- list()

for (k in seq_len(n_trials)) {
  # --- item selection at the ability estimate *before* this trial's response ---
  # catR's `out` holds the 1-based indices of the already administered items
  # (NULL when none), `x` the corresponding responses. This mirrors the call
  # used in scripts/generate_reference.R.
  sel <- nextItem(
    itemBank  = bank,
    theta     = theta,
    out       = if (length(adm_catr) == 0) NULL else adm_catr,
    x         = if (length(adm_catr) == 0) NULL else resp_so_far,
    criterion = "MFI"
  )

  # --- administer the logged item and response ---
  adm_catr    <- c(adm_catr, administered[k] + 1L)
  resp_so_far <- c(resp_so_far, responses[k])
  it <- bank[adm_catr, , drop = FALSE]

  # --- ability estimate and SE after the response ---
  theta <- as.numeric(thetaEst(it, resp_so_far, method = "EAP",
                               priorDist = PRIOR_DIST, priorPar = PRIOR_PAR,
                               D = D_SCALE, parInt = PAR_INT))
  se <- as.numeric(semTheta(theta, it, resp_so_far, method = "EAP",
                            priorDist = PRIOR_DIST, priorPar = PRIOR_PAR,
                            D = D_SCALE, parInt = PAR_INT))

  steps[[k]] <- list(
    trial                    = k,
    administered_item_0based = as.integer(sel$item) - 1L,
    info                     = as.numeric(sel$info),
    theta                    = theta,
    se                       = se
  )

  cat(sprintf("  trial %2d: MFI picks item %3d (logged %3d)  info=%10.4f  theta=%12.9f  se=%12.9f\n",
              k, as.integer(sel$item) - 1L, administered[k],
              as.numeric(sel$info), theta, se))
}

ref <- list(
  r_version    = paste(R.version$major, R.version$minor, sep = "."),
  catr_version = as.character(packageVersion("catR")),
  input        = basename(in_json),
  n_items      = nrow(bank),
  n_trials     = n_trials,
  selection    = "MFI",
  estimation   = list(method = "EAP", priorDist = PRIOR_DIST,
                      priorPar = PRIOR_PAR, D = D_SCALE, parInt = PAR_INT),
  final_theta  = theta,
  steps        = steps
)

dir.create(dirname(out_json), showWarnings = FALSE, recursive = TRUE)
write_json(ref, out_json, digits = 16, auto_unbox = TRUE)
cat("Wrote reference to:", out_json, "\n")
